public class String1 {
    public static void main(String[] args) {
        // basics of strings
        String str="Adarsh";
        // System.out.print(str);
        for(int i=0;i<str.length();i++){
            System.out.print(str.charAt(i)+ " ");// charAt method is used to access elements from string.
        }
    }
    
}
